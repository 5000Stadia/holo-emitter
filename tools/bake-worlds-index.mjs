#!/usr/bin/env node
/* bake-worlds-index.mjs — the worlds a visitor can switch between, DERIVED.
 *
 * [Kabe, 2026-08-30] "Can I get a toggle on the demo to switch between demos."
 * The page cannot read a directory, so the list rides as fixtures/index.js the
 * way every other baked truth does. One entry per PACK whose visitor world is
 * baked: the id is the pack's own `paths.world_query`, the label its title.
 * Nothing here names a theme; add a pack, re-run, and the switch knows it. */
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const worlds = [];
for (const name of readdirSync(join(root, "packs")).sort()) {
  const dir = join(root, "packs", name);
  const packFile = join(dir, "pack.json");
  const worldFile = join(dir, "world.json");
  if (!existsSync(packFile) || !existsSync(worldFile)) continue;
  const pack = JSON.parse(readFileSync(packFile, "utf8"));
  const world = JSON.parse(readFileSync(worldFile, "utf8"));
  const id = world.paths && world.paths.world_query;
  if (!id || !/^[A-Za-z0-9_-]+$/.test(id)) continue;
  if (!existsSync(join(root, "fixtures", id, "fixture.js"))) continue;   // not baked: not offered
  worlds.push({ id, title: pack.title || id });
}
const out = "// GENERATED by tools/bake-worlds-index.mjs — the packs whose visitor world is baked.\n" +
  "window.HOLO_WORLDS = " + JSON.stringify(worlds, null, 1) + ";\n";
writeFileSync(join(root, "fixtures", "index.js"), out);
console.log(`baked fixtures/index.js (${worlds.length} world(s): ${worlds.map(w => w.id).join(", ")})`);
