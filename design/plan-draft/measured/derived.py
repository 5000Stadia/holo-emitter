# ------------------------------------------------------------------ the check

def _state():
    return _read_json(STATE_PATH, {}) or {}


def check(only=None, deep=False):
    """What is stale, and why. Writes nothing. Returns a list of records."""
    st = _state().get("artifacts", {})
    out = []
    for a in ARTIFACTS:
        if only and a["id"] != only:
            continue
        rec = {"id": a["id"], "paths": a["paths"],
               "invalidated_by": a["invalidated_by"], "regen": a["regen"],
               "state": FRESH, "why": []}
        missing = [p for p in a["paths"] if not os.path.exists(os.path.join(ROOT, p))]
        if missing:
            rec["state"] = STALE
            rec["why"] = [(p, "it has never been written") for p in missing]
            out.append(rec)
            continue
        if a.get("witness"):
            bad = a["witness"]()
            if bad:
                rec["state"] = STALE
                rec["why"] = bad
        else:
            digest, n = input_digest(a["inputs"], a["paths"])
            rec["inputs"] = n
            was = (st.get(a["id"]) or {}).get("input_digest")
            if was is None:
                rec["state"] = UNPROVEN
                rec["why"] = [(a["paths"][0],
                               "nothing records what this was last derived from, "
                               "so it cannot be shown fresh — run the regen once")]
            elif was != digest:
                rec["state"] = STALE
                rec["why"] = [(a["paths"][0],
                               "its inputs have moved since it was last derived "
                               "(%d inputs; %s -> %s)" % (n, was[:12], digest[:12]))]
        if deep and a.get("deep"):
            bad = a["deep"](a["paths"])
            rec["deep"] = "stale" if bad else "fresh"
            if bad and rec["state"] == FRESH:
                rec["state"] = STALE
                rec["why"] = [(p, w + " — and the fast check called it fresh, "
                               "which is a defect in this file's input set") for p, w in bad]
            elif bad:
                rec["why"] += bad
            elif not bad and rec["state"] == STALE and not a.get("witness"):
                rec["why"].append((a["paths"][0],
                                   "NOTE: a fresh run writes the same bytes; the "
                                   "input digest is merely unrecorded for these inputs"))
        out.append(rec)
    return out


def is_stale(records):
    return [r for r in records if r["state"] != FRESH]


# ------------------------------------------------------------------ the regen

#: One artifact is another's input, so regenerating the first stales the second
#: — the snapped readings feed the material audit, the strip records feed the
#: room measure. The registry is ordered upstream-first so one pass settles it;
#: this loop is what makes that an assertion rather than a hope, and it is
#: bounded because a cycle would otherwise be a hang.
MAX_ROUNDS = 4


def regenerate(only=None, verbose=True):
    """Regenerate exactly what the check calls stale, once per action.

    Returns `(records, wrote, notes)`. Each action is clocked as `derive.regen`
    with the artifact it was run for and what it wrote, so the row-33 ledger can
    say what a sweep's derivation cost.

    IDEMPOTENT BY CONSTRUCTION, at two levels: nothing runs whose artifacts the
    check calls fresh, and every action writes through `_write_if_moved`, so an
    action that runs anyway (because one of a shared pair was stale) still moves
    no bytes it does not have to.
    """
    first = check(only=only)
    wrote_all, notes = [], []
    for _round in range(MAX_ROUNDS):
        records = first if _round == 0 else check(only=only)
        stale = is_stale(records)
        if not stale:
            break
        done = set()
        moved = False
        for r in stale:
            a = BY_ID[r["id"]]
            act = a.get("action")
            if act is None:
                notes.append("%s: %s" % (r["id"], r["regen"]))
                continue
            if act in done:
                continue
            done.add(act)
            t0 = time.time()
            wrote, why = ACTIONS[act](r["why"] if a.get("witness") else None)
            # REFUSED MEANS NOTHING WAS WRITTEN AND THE TOOL SAID WHY. An action
            # also returns a NOTE where it did the work in the second of its two
            # licensed ways — the strip record marked `stale_from` rather than
            # re-cut — and a first draft flagged that as a refusal, which would
            # have put a successful derivation in the ledger's failure column.
            timings.record("derive.regen", t0, time.time(), r["id"],
                           {"action": act, "wrote": wrote[:12], "files": len(wrote),
                            "refused": bool(why) and not wrote,
                            "note": (why or "")[:300] or None})
            wrote_all += wrote
            moved = moved or bool(wrote)
            if why:
                notes.append("%s: %s" % (r["id"], why))
            if verbose:
                print("  %-24s %s" % (r["id"], ", ".join(wrote) if wrote else
                                      (why or "nothing moved")))
        _record_state(only=only)
        if not moved:
            break
    return first, wrote_all, notes


def _record_state(only=None):
    """What each artifact was last derived from. See STATE_PATH."""
    st = _state()
    arts = st.setdefault("artifacts", {})
    st["_what_this_is"] = (
        "What every derived artifact was last regenerated FROM, written by "
        "design/plan-draft/measured/derived.py. `--check` recomputes each input "
        "digest and reports an artifact whose inputs have moved. Do not hand-edit: "
        "an entry here is a claim that the artifact beside it was written from "
        "exactly these bytes.")
    for a in ARTIFACTS:
        if only and a["id"] != only:
            continue
        if a.get("witness") or not a.get("inputs"):
            continue
        digest, n = input_digest(a["inputs"], a["paths"])
        arts[a["id"]] = {"input_digest": digest, "inputs": n,
                         "artifacts": {p: sha(os.path.join(ROOT, p)) for p in a["paths"]},
                         "at": time.strftime("%Y-%m-%dT%H:%M:%S")}
    _write_if_moved(STATE_PATH, (json.dumps(st, indent=2, sort_keys=True) + "\n").encode())


# --------------------------------------------------------------------- the CLI

def _print(records):
    for r in records:
        mark = {FRESH: "fresh ", STALE: "STALE ", UNPROVEN: "UNPROVEN"}[r["state"]]
        print("%s %-24s %s" % (mark, r["id"], ", ".join(r["paths"])))
        for p, w in r["why"]:
            print("         %s: %s" % (p, w))
        if r["state"] != FRESH:
            print("         remake: %s" % r["regen"])


