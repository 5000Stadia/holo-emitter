def _deep_cmp(paths, run_into):
    """Regenerate into a temp directory and byte-compare. `run_into(tmp)` returns
    a dict of {committed path -> the temp file that should equal it}."""
    tmp = tempfile.mkdtemp(prefix="holo-derive-deep-")
    try:
        pairs, why = run_into(tmp)
        if why:
            return [(paths[0], why)]
        bad = []
        for committed, fresh in pairs.items():
            a = os.path.join(ROOT, committed)
            if not os.path.exists(fresh):
                bad.append((committed, "a fresh run wrote nothing to compare against"))
            elif not os.path.exists(a) or open(a, "rb").read() != open(fresh, "rb").read():
                bad.append((committed, "a fresh run of its generator writes different bytes"))
        return bad
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


