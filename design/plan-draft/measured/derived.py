#!/usr/bin/env python3
"""Every artifact this pipeline DERIVES, what invalidates it, and how it is remade.

    python3 design/plan-draft/measured/derived.py --check
    python3 design/plan-draft/measured/derived.py --check --json
    python3 design/plan-draft/measured/derived.py --check --deep
    python3 design/plan-draft/measured/derived.py --regen [--only <id>]

    python3 design/plan-draft/measured/row23_run.py --derive-check   # the same check

WHY THIS FILE EXISTS. [production law clause 6] "Your solutions need to fold
into the generation method for future builds" — a correction lands in the
EMITTER, a GATE or the INSTRUMENT, never in a hand-retouched artifact.

Eight suite cases were red on `main` whenever the manor loop had run and green
on a frozen tree, and every one of them compared a COMMITTED GENERATED ARTIFACT
against a live store that had moved under it. The loop promotes a wall,
supersedes a wall, re-snaps a frame or paints a door void — and the artifacts
those acts invalidate were regenerated by whichever command the Navigator
happened to type next. So the ledger tick shipped stale derived files, and the
suite read that as breakage. The defect is not in any of the eight cases and
not in any of the artifacts: it is that nothing in the machine knew WHICH
ARTIFACT EACH ACT INVALIDATES. This file is that knowledge, in one place.

    THE TABLE — artifact -> what invalidates it

    material_provenance.json     any promotion or supersede (the ask a painting
                                 was made from is read off the store), any edit
                                 to the voice table or the composer
    material_legacy.json         the same: the ledger admits one facing from one
                                 exact candidate, so a re-ask closes a line
    room_consistency.json        any promotion or supersede in a measured room
    row40-consistency/README.md  the same (its hand-written tail is kept)
    window_calibration.json      any promotion or supersede (it is the list of
                                 promoted walls the window clause cannot see)
    row35snap/<loc>-<F>.json     a re-snap: the frame a reading describes is
      + its snapped.png          rewritten under the reading that describes it
    row36doors/<loc>-<F>.json    a re-repair, or a change to the snapped frame
      + its doored.png           the voids were painted onto
    manor/retries.json           a neighbour's RE-PROMOTION: an edge strip was
      (edge_seed records)        cut from a painting the store has replaced
    backdrops/<loc>/<F>.meta     the candidate it names, and the reading that
      + <F>.png                  candidate was measured in
    backdrops/baked.js           any promotion (the picture the page renders)
    fixtures/*/fixture.js        any promotion (the meta the page renders with)

TWO MODES, AND THE FAST ONE IS THE ONE THE GUARDS SHARE.

  `--check`  asks every artifact whether it is stale WITHOUT WRITING ANYTHING.
             It is what `tools/publish-site.sh` refuses on and what the suite's
             own freshness helper reads, so the publish preflight and the
             tests cannot disagree about what fresh means. Two kinds of answer
             stand behind it: a WITNESS the artifact carries itself (a reading
             records the digest of the frame it describes — nothing has to be
             regenerated to know it has gone stale) and, where an artifact
             carries no witness, the digest of its INPUT SET recorded in
             `derived-state.json` when it was last derived. An input digest
             includes the GENERATOR'S OWN SOURCE, because a change to the
             instrument stales its output exactly as a change to the store does.

  `--deep`   regenerates into a temporary tree and compares BYTE FOR BYTE. It is
             the honest answer and it costs about half a minute; it exists so
             that the fast answer is a claim that can be checked rather than one
             that has to be believed. `--check --deep` runs both and reports a
             disagreement between them as a finding of its own.

IDEMPOTENT, AND IT SAYS SO. `--regen` runs only the actions whose artifacts the
check calls stale, writes only files whose bytes actually move, and prints what
it did and did not do. A second run regenerates nothing and says `nothing to
regenerate`. Every action is clocked into the row-33 ledger as `derive.regen`,
one record per artifact, with what it wrote.

WHAT THIS FILE WILL NOT DO. It never decides which candidate a wall ships — that
is the sweep's, and it is made of measurements. When a reading and the frame it
describes disagree, the reading is the record of a measurement that was taken
and the frame is a picture that can be recomputed from it, so the FRAME is
re-derived from the candidate the reading names. If that reproduces different
bytes, the pair is refused with the reason rather than quietly rewritten.
"""
