def snap_frame(loc, fac):
    """Where a wall's snapped frame lives — `row23_run.SNAP_SOURCE_DIR`'s rule.

    A function rather than a constant because everything here is addressed
    relative to ROOT, and a path frozen at import time is a path that stops
    meaning what it says the moment ROOT is anything but this checkout — which
    `test_derived.py` does deliberately, and which caught this exact coupling.
    """
    return os.path.join(ROOT, "backdrops", "source-snapped",
                        "%s-%s" % (loc, fac), "snapped.png")


def door_frame(loc, fac):
    """And where its repaired one does. See `row23_run.DOOR_SOURCE_DIR`."""
    return os.path.join(ROOT, "backdrops", "source-doors",
                        "%s-%s" % (loc, fac), "doored.png")

#: Where the input digests live. Excluded from every input set by construction —
#: see `_is_own` — because a record of what everything was derived from cannot
#: also be one of the things they were derived from: it would move every time
#: anything moved, and nothing could ever settle.
STATE_PATH = os.path.join(HERE, "derived-state.json")

FRESH, STALE, UNPROVEN = "fresh", "stale", "unproven"


# --------------------------------------------------------------- small tools

def rel(p):
    return os.path.relpath(os.path.abspath(p), ROOT)


def sha(p):
    """sha256 of a file, or None where there is no file."""
    if not os.path.exists(p):
        return None
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _read_json(p, default=None):
    try:
        with open(p) as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return default


def _run(cmd, cwd=None):
    """A generator, run. Returns (ok, output) and never raises on a refusal."""
    r = subprocess.run(cmd, cwd=cwd or ROOT, capture_output=True, text=True,
                       env=dict(os.environ, HOLO_TIMINGS="off"))
    return r.returncode == 0, (r.stdout + r.stderr).strip()


# ------------------------------------------------------------- the input set

#: ONE ARTIFACT MAY BE ANOTHER'S INPUT — a snapped reading is derived, and the
#: material audit genuinely reads it — so the registry is a DAG and not a flat
#: list, and `regenerate` runs to a fixed point. What may never be an input is an
#: artifact's own output (nothing can settle if it is) or the digest record
#: itself.
def _is_own(r, own):
    return r == rel(STATE_PATH) or any(r == o or r.startswith(o + "/") for o in own)


def _expand(patterns, own=()):
    out = set()
    for pat in patterns:
        for p in glob.glob(os.path.join(ROOT, pat), recursive=True):
            if os.path.isfile(p) and not _is_own(rel(p), own):
                out.add(rel(p))
    return sorted(out)


def input_digest(patterns, own=()):
    """One digest over (path, content) for every input, sorted.

    The PATH is hashed beside the bytes so that adding or removing a file moves
    the digest even when the bytes that remain are unchanged — a promotion that
    adds a wall must stale the audit that counts walls.
    """
    h = hashlib.sha256()
    n = 0
    for r in _expand(patterns, own):
        h.update(r.encode("utf-8"))
        h.update(b"\0")
        h.update((sha(os.path.join(ROOT, r)) or "").encode("ascii"))
        h.update(b"\n")
        n += 1
    return h.hexdigest(), n


