# ------------------------------------------------------------ the witnesses
#
# A WITNESS is a check the artifact can answer about ITSELF, off its own record,
# with nothing regenerated. Where one exists it is the authority and the input
# digest is not consulted: it is exact, it is cheap, and it names the wall.

def _snap_pairs():
    """(key, reading path, frame path, source candidate) for every snapped
    reading in the production round."""
    out = []
    d = os.path.join(HERE, SNAP_ROUND)
    if not os.path.isdir(d):
        return out
    for f in sorted(os.listdir(d)):
        if not f.endswith(".json"):
            continue
        doc = _read_json(os.path.join(d, f))
        if not doc:
            continue
        loc, fac = f[:-5].rsplit("-", 1)
        snap = doc.get("_snap") or {}
        frame = None
        said = str(doc.get("_what_this_is") or "")
        mark = "The image it describes is "
        if mark in said:
            frame = said.split(mark, 1)[1].split(".png", 1)[0] + ".png"
        #: A frame the reading names from OUTSIDE the tree is not a frame this
        #: repository has: the pilot batch and the production round both live
        #: under ROOT, and anything else is a reading written by a run that
        #: staged its output somewhere temporary. Such a reading is re-derived
        #: at the production path rather than followed off the edge of the tree.
        escaped = bool(frame) and (frame.startswith("..") or os.path.isabs(frame))
        out.append({"key": "%s/%s" % (loc, fac), "doc": rel(os.path.join(d, f)),
                    "frame": None if escaped else frame, "escaped": escaped,
                    "production_frame": rel(snap_frame(loc, fac)),
                    "candidate": snap.get("source_candidate"),
                    "recorded": doc.get("_source_sha256")})
    return out


def witness_snap_readings():
    """A snapped reading must describe the frame that is on disk.

    THIS IS THE SEAM ITSELF. `backdrops/source-snapped/<loc>-<F>/snapped.png` is
    keyed by WALL and not by candidate, so a later pass that snaps a newer roll
    of the same wall overwrites the frame a promoted wall was measured on — and
    the reading, the promoted meta and the store's own picture then describe a
    picture that is no longer there. Three walls were in exactly that state when
    this file was written, and `snap.spec`, `assembly.spec` and `fixtures.spec`
    were each red for it in a different language.
    """
    bad = []
    for p in _snap_pairs():
        if p["escaped"]:
            bad.append((p["doc"], "the reading names a frame outside this tree, so "
                                  "nothing here can be the image it describes"))
            continue
        if not p["frame"]:
            bad.append((p["doc"], "the reading does not name the image it describes"))
            continue
        fp = os.path.join(ROOT, p["frame"])
        if not os.path.exists(fp):
            bad.append((p["doc"], "it names %s and there is no such frame" % p["frame"]))
            continue
        got = sha(fp)
        if got != p["recorded"]:
            bad.append((p["doc"],
                        "%s is not the frame this reading was written for "
                        "(records %s, the frame on disk is %s) — the wall was "
                        "re-snapped on another roll and the frame was rewritten "
                        "under the reading"
                        % (p["frame"], (p["recorded"] or "-")[:12], (got or "-")[:12])))
    return bad


def witness_door_readings():
    """A door-void reading must describe the repaired frame that is on disk."""
    bad = []
    d = os.path.join(HERE, DOOR_ROUND)
    if not os.path.isdir(d):
        return bad
    for f in sorted(os.listdir(d)):
        if not f.endswith(".json"):
            continue
        doc = _read_json(os.path.join(d, f)) or {}
        r = doc.get("_doors_repair") or {}
        img = r.get("image")
        if not img:
            bad.append((rel(os.path.join(d, f)),
                        "the reading carries no `_doors_repair.image`, so nothing "
                        "says which frame it describes"))
            continue
        got = sha(os.path.join(ROOT, img))
        if got is None:
            bad.append((rel(os.path.join(d, f)), "it names %s and there is no such frame" % img))
        elif got != doc.get("_source_sha256"):
            bad.append((rel(os.path.join(d, f)),
                        "%s is not the repaired frame this reading was written for" % img))
    return bad


def promoted_walls():
    """(key, meta path, candidate) for every promoted wall in the store."""
    out = []
    b = os.path.join(ROOT, "backdrops")
    for loc in sorted(os.listdir(b)):
        d = os.path.join(b, loc)
        if not os.path.isdir(d) or loc.startswith("source"):
            continue
        for f in "NESW":
            mp = os.path.join(d, "%s.meta.json" % f)
            if not os.path.exists(mp):
                continue
            m = _read_json(mp) or {}
            cand = str(m.get("camera_id") or "").replace("measured:", "") or None
            out.append({"key": "%s/%s" % (loc, f), "meta": rel(mp), "candidate": cand,
                        "png": rel(os.path.join(d, "%s.png" % f)),
                        "round": m.get("measured_round")})
    return out


def witness_promoted_metas():
    """The store's picture is a byte copy of the candidate its meta names, and
    the reading that candidate was measured in describes that candidate.

    This is `fixtures.spec`'s promotion-staleness case made cheap. That case
    re-runs the whole promotion into a staged tree and byte-compares the meta,
    which is the honest check and costs a minute; what it can catch that nothing
    else can is a meta written from a picture that has since been replaced — and
    THAT is answerable from two digests. Where they disagree the promotion has
    to be run again, and this says which wall and why.
    """
    bad = []
    for w in promoted_walls():
        if not w["candidate"]:
            bad.append((w["meta"], "the meta names no candidate at all"))
            continue
        cp = os.path.join(ROOT, w["candidate"])
        if not os.path.exists(cp):
            bad.append((w["meta"], "it names a candidate that is not in the tree: %s"
                        % w["candidate"]))
            continue
        if sha(cp) != sha(os.path.join(ROOT, w["png"])):
            bad.append((w["png"],
                        "the store's picture is not a byte copy of %s, the candidate "
                        "its own meta names — the frame moved after the promotion"
                        % w["candidate"]))
        loc, fac = w["key"].split("/")
        doc = os.path.join(HERE, w["round"] or "", "%s-%s.json" % (loc, fac))
        d = _read_json(doc)
        if d is None:
            bad.append((w["meta"], "its measurement round (%s) holds no reading for it"
                        % (w["round"] or "the top round")))
        elif d.get("_source_sha256") and d["_source_sha256"] != sha(cp):
            bad.append((rel(doc),
                        "the reading %s was promoted from does not describe %s"
                        % (w["key"], w["candidate"])))
    return bad


def _edge_seed_entries():
    doc = _read_json(RETRIES_FILE) or {}
    return [e for e in doc.get("entries", []) if e.get("edge_seed")]


def _seed_rolled(e):
    """Has the packet this strip was cut for already been painted?

    A strip is TWO things at once: the reference image a packet carries, and a
    record of what was handed to the painter. Once a roll has come back the
    strip is evidence and may not be recut — the record would then describe an
    ask nobody made. Before any roll it is only an input, and an input cut from
    a painting the store has replaced is simply wrong.
    """
    for r in e.get("rolls") or []:
        if r.get("candidate") and os.path.exists(os.path.join(ROOT, r["candidate"])):
            return r["candidate"]
    return None


def witness_edge_seeds():
    """Every recorded strip is the strip on disk, cut from the painting on disk.

    `seams.spec` reads this record and re-hashes both files. What breaks it is a
    neighbour's RE-PROMOTION: the strip was cut from `backdrops/<loc>/<F>.png`
    and that wall has since been superseded, so the source digest in the record
    is a digest of bytes that are gone.
    """
    bad = []
    for e in _edge_seed_entries():
        s = e["edge_seed"]
        f = os.path.join(ROOT, s["file"])
        if not os.path.exists(f):
            bad.append((s["file"], "%s's recorded strip is not on disk" % e["key"]))
        elif sha(f) != s.get("sha256"):
            bad.append((s["file"], "%s's strip is not the bytes the record names" % e["key"]))
        src = os.path.join(ROOT, s["source"])
        got = sha(src)
        if got is None:
            bad.append((s["source"], "%s's seed source painting is gone" % e["key"]))
        elif got != s.get("source_sha256"):
            stale = s.get("stale_from") or {}
            if stale.get("source_sha256") == s.get("source_sha256") and \
                    stale.get("now_sha256") == got:
                continue          # recorded, with its reason — see `_regen_edge_seeds`
            bad.append((s["source"],
                        "%s's strip was cut from %s at %s and the store now holds %s "
                        "there — the neighbour was re-promoted under the record"
                        % (e["key"], s["source"], (s.get("source_sha256") or "-")[:12],
                           got[:12])))
    return bad


# ------------------------------------------------------------- the actions
#
# One action per artifact family. Each returns (paths_written, note); it writes
# only where the bytes actually move, so a second run writes nothing and the
# caller can say so.

def _write_if_moved(path, data):
    """Write `data` (bytes) at `path` only if it is not already there."""
    if os.path.exists(path):
        with open(path, "rb") as fh:
            if fh.read() == data:
                return False
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(data)
    return True


def _regen_materials(_findings=None):
    """`--audit-materials --seal-legacy`: the provenance report and the ledger.

    `--warn-only` because this is the REGENERATION and not the gate: the gate is
    the same command run without it, and a run that refused to write the report
    describing a store it disapproves of would leave the stale report in place.
    """
    before = {p: sha(p) for p in (
        os.path.join(HERE, "material_provenance.json"),
        os.path.join(HERE, "material_legacy.json"))}
    ok, out = _run(["node", os.path.join(ROOT, "tools", "make-scaffold.mjs"),
                    "--audit-materials", "--seal-legacy", "--warn-only"])
    if not ok:
        return [], "make-scaffold refused: " + out.split("\n")[-1][:200]
    moved = [rel(p) for p, s in before.items() if sha(p) != s]
    return moved, None


def _regen_room_consistency(_findings=None):
    """The per-room measure, and its README — whose hand-written tail is kept by
    `room_consistency.kept_tail`, which is why this runs the tool rather than
    writing the file itself."""
    paths = [os.path.join(HERE, "room_consistency.json"),
             os.path.join(ROOT, "design", "batches", "row40-consistency", "README.md")]
    before = {p: sha(p) for p in paths}
    ok, out = _run(["python3", os.path.join(HERE, "room_consistency.py")])
    if not ok:
        return [], "room_consistency refused: " + out.split("\n")[-1][:200]
    return [rel(p) for p, s in before.items() if sha(p) != s], None


def _regen_window_calibration(_findings=None):
    p = os.path.join(HERE, "window_calibration.json")
    before = sha(p)
    ok, out = _run(["python3", os.path.join(HERE, "window_measure.py"),
                    "--calibrate", "--write", p])
    if not ok:
        return [], "window_measure refused: " + out.split("\n")[-1][:200]
    return ([rel(p)] if sha(p) != before else []), None


def _snap_pair_regen(key, candidate, doc_path, frame_path):
    """Re-derive ONE snapped frame and its reading from the roll the reading
    names. Deterministic — `snap.spec` asserts it — so a pair that is already
    consistent comes back byte-identical and nothing moves.

    THE FRAME IS WRITTEN AT ITS REAL PATH AND NOT STAGED, because the reading
    the snap writes NAMES the file it was told to write ("The image it describes
    is …") and `snap.spec` reads that sentence to find the frame. A first draft
    snapped into a temp directory and copied the two files into place; the copy
    of the reading then named a frame in `/tmp` that no longer existed, which is
    the very defect this artifact exists to prevent, authored by its repair. The
    frame's previous bytes are held instead, and put back if the snap refuses
    part-way — `row35_snap.snap_to_round` writes the picture before the reading,
    so a refusal between the two would otherwise leave exactly the mismatch
    being repaired.
    """
    import row35_snap
    before = None
    if os.path.exists(frame_path):
        with open(frame_path, "rb") as fh:
            before = fh.read()
    tmp = tempfile.mkdtemp(prefix="holo-derive-snap-")
    try:
        out_doc = os.path.join(tmp, "reading.json")
        res, why = row35_snap.snap_to_round(
            key, candidate, round_dir=SNAP_ROUND, out_png=frame_path, doc_out=out_doc)
        if res is None:
            if before is not None:
                _write_if_moved(frame_path, before)
            return [], ("the snap refuses the roll this reading names (%s): %s"
                        % (candidate, why))
        wrote = []
        with open(frame_path, "rb") as fh:
            if fh.read() != before:
                wrote.append(rel(frame_path))
        with open(out_doc, "rb") as fh:
            if _write_if_moved(doc_path, fh.read()):
                wrote.append(rel(doc_path))
        return wrote, None
    except Exception:
        if before is not None:
            _write_if_moved(frame_path, before)
        raise
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _regen_snap_readings(findings=None):
    """Every snapped pair the witness calls stale, re-derived from its own roll.

    THE READING IS THE RECORD AND THE FRAME IS THE PICTURE. A reading is what an
    instrument measured, it names the roll it was measured on, and the promoted
    meta beside it carries the same numbers; the frame is a warp of that roll and
    can be recomputed exactly. So the frame is brought back to the reading and
    never the other way round. Which roll SHOULD win is the sweep's decision and
    is made of measurements — this only makes the pair describe one picture.
    """
    wrote, notes = [], []
    stale = {p for p, _ in (findings or witness_snap_readings())}
    for p in _snap_pairs():
        if p["doc"] not in stale:
            continue
        if not p["candidate"]:
            notes.append("%s: the reading names no roll to re-derive it from" % p["doc"])
            continue
        if not os.path.exists(os.path.join(ROOT, p["candidate"])):
            notes.append("%s: the roll it names (%s) is not in the tree"
                         % (p["doc"], p["candidate"]))
            continue
        w, why = _snap_pair_regen(p["key"], p["candidate"],
                                  os.path.join(ROOT, p["doc"]),
                                  os.path.join(ROOT, p["frame"] or p["production_frame"]))
        wrote += w
        if why:
            notes.append("%s: %s" % (p["doc"], why))
    return wrote, ("; ".join(notes) or None)


def _regen_door_readings(findings=None):
    """A repaired frame and its reading, re-derived: snap the roll, paint the
    plan's voids onto it, re-read the doors off the result.

    The two halves are `row36_assemble.repair_doors` and `row23_run._doors_
    document`, called in the order the sweep's own void-repair exit calls them,
    because a second implementation of that order is a second answer to which
    document a promotion reads.
    """
    import row23_run
    import row36_assemble
    wrote, notes = [], []
    stale = {p for p, _ in (findings or witness_door_readings())}
    d = os.path.join(HERE, DOOR_ROUND)
    plan = _read_json(PLAN)
    facings = row36_assemble.read_json(row36_assemble.FACINGS)["facings"]
    for f in sorted(os.listdir(d) if os.path.isdir(d) else []):
        if not f.endswith(".json") or rel(os.path.join(d, f)) not in stale:
            continue
        loc, fac = f[:-5].rsplit("-", 1)
        key = "%s/%s" % (loc, fac)
        snap_doc = _read_json(os.path.join(HERE, SNAP_ROUND, f))
        cand = ((snap_doc or {}).get("_snap") or {}).get("source_candidate")
        if not cand:
            notes.append("%s: no snapped reading names the roll this was repaired from" % key)
            continue
        # The snapped half first: the voids are painted onto THAT frame, so a
        # repair over a stale one would carry the stale one forward.
        frame = snap_frame(loc, fac)
        w, why = _snap_pair_regen(key, cand, os.path.join(HERE, SNAP_ROUND, f), frame)
        wrote += w
        if why:
            notes.append("%s: %s" % (key, why))
            continue
        out_png = door_frame(loc, fac)
        tmp = tempfile.mkdtemp(prefix="holo-derive-doors-")
        try:
            staged = os.path.join(tmp, "doored.png")
            rec, why = row36_assemble.repair_doors(key, rel(frame), staged, plan, facings)
            if rec is None:
                notes.append("%s: the door repair refuses this frame: %s" % (key, why))
                continue
            with open(staged, "rb") as fh:
                if _write_if_moved(out_png, fh.read()):
                    wrote.append(rel(out_png))
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        res = {"candidate": rel(frame), "doc_out": os.path.join(HERE, SNAP_ROUND, f)}
        before = sha(os.path.join(d, f))
        doc_out, why = row23_run._doors_document(key, res, rel(out_png), rec)
        if doc_out is None:
            notes.append("%s: %s" % (key, why))
            continue
        if sha(doc_out) != before:
            wrote.append(rel(doc_out))
    return wrote, ("; ".join(notes) or None)


def _regen_edge_seeds(findings=None):
    """The strip records in `retries.json`, against the store as it stands now.

    TWO OUTCOMES, AND WHICH ONE IS NOT A JUDGEMENT CALL. A packet that has NOT
    been rolled yet is an ask still waiting to go out, so its strip is re-cut
    from the neighbour's current painting and the record is updated — the
    painter must be handed the wall that is in the store. A packet that HAS been
    rolled is history: the strip is what was actually sent, re-cutting it would
    make the record describe an ask nobody made, so the record is marked
    `stale_from` with both digests, the roll that consumed it, and the reason.
    Row 38's claim is about the ask that went out, and that claim stays exactly
    as strong; what changes is that the drift is now written down instead of
    turning a suite case red.
    """
    doc = _read_json(RETRIES_FILE)
    if not doc:
        return [], "there is no retries.json to regenerate"
    wrote, notes, changed = [], [], False
    stale_sources = {p for p, _ in (findings or witness_edge_seeds())}
    for e in doc.get("entries", []):
        s = e.get("edge_seed")
        if not s or s["source"] not in stale_sources:
            continue
        src = os.path.join(ROOT, s["source"])
        now = sha(src)
        if now is None:
            notes.append("%s: its seed source %s is gone from the store"
                         % (e["key"], s["source"]))
            continue
        if now == s.get("source_sha256"):
            continue
        rolled = _seed_rolled(e)
        if rolled:
            s["stale_from"] = {
                "source_sha256": s.get("source_sha256"),
                "now_sha256": now,
                "rolled": rolled,
                "why": ("the strip this packet carried was cut from %s as it stood "
                        "when the ask went out; that neighbour has since been "
                        "re-promoted, and the ask cannot be un-sent. The strip and "
                        "its digest are what was handed to the painter and are left "
                        "exactly as they were." % s["source"]),
                "at": time.strftime("%Y-%m-%dT%H:%M:%S"),
            }
            changed = True
            notes.append("%s: marked stale_from (already rolled as %s)"
                         % (e["key"], os.path.basename(rolled)))
            continue
        # THE SIDE THAT IS CUT IS THE NEIGHBOUR'S, not this wall's: `side` is the
        # edge of THIS picture the strip sits at and `neighbour_edge` is the edge
        # of THAT painting the columns come from. `tools/edge-seed.mjs` passes
        # `plan_.neighbour_edge` for exactly this reason and the re-cut has to
        # ask the same question or it would hand the painter the far side of the
        # room. Same script, same fraction, same positional CLI.
        ok, out = _run(["python3", os.path.join(ROOT, "tools", "crop-edge-seed.py"),
                        s["source"], s["file"], s["neighbour_edge"],
                        str(s.get("fraction", 0.1))])
        if not ok:
            notes.append("%s: the strip could not be re-cut: %s"
                         % (e["key"], out.split("\n")[-1][:160]))
            continue
        s["sha256"] = sha(os.path.join(ROOT, s["file"]))
        s["source_sha256"] = now
        s["recut"] = {"at": time.strftime("%Y-%m-%dT%H:%M:%S"),
                      "why": ("the neighbour was re-promoted before this packet was "
                              "rolled, so the ask carries the painting the store "
                              "actually holds")}
        changed = True
        wrote.append(s["file"])
        notes.append("%s: strip re-cut from the current %s" % (e["key"], s["source"]))
    if changed:
        # `ensure_ascii=False` because the emitter that writes this file is
        # node's `JSON.stringify`, which does not escape a non-ASCII character —
        # and every correction sentence in here carries an em dash. Writing it
        # back the python default way turned a one-line change into a 221-line
        # diff of `—` churn, which is the record made unreadable by the
        # tool that keeps it.
        data = (json.dumps(doc, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
        if _write_if_moved(RETRIES_FILE, data):
            wrote.append(rel(RETRIES_FILE))
    return wrote, ("; ".join(notes) or None)


def bake(root=ROOT):
    """`backdrops/baked.js` and every fixture that reads a promoted meta.

    ONE HOME FOR THE BAKE COMMANDS. `row23_run._bake` is this function with the
    sweep's own stopwatch around it; the publish preflight and `--regen` reach it
    here. A promoted wall changes two baked artifacts and not one — the picture
    and the meta the page renders it with — and baking only the first is how a
    sweep leaves `fixtures/nav-manor/fixture.js` stale.
    """
    out = []
    r = subprocess.run(["node", os.path.join(root, "tools", "bake-backdrops.mjs")],
                       cwd=root, capture_output=True, text=True)
    if r.returncode != 0:
        return 0, "backdrops/baked.js: " + (r.stdout + r.stderr).strip()[-300:]
    n = 0
    for d in sorted(os.listdir(os.path.join(root, "fixtures"))):
        fd = os.path.join(root, "fixtures", d)
        if not os.path.exists(os.path.join(fd, "world.json")):
            continue
        r = subprocess.run(["node", os.path.join(root, "tools", "bake-fixtures.mjs"),
                            "--fixture-dir", fd], cwd=root,
                           capture_output=True, text=True)
        n += 1
        if r.returncode != 0:
            out.append("fixtures/%s: %s" % (d, (r.stdout + r.stderr).strip()[-300:]))
    return n, (out[0] if out else None)


def _regen_bake(_findings=None):
    before = {p: sha(p) for p in
              [os.path.join(ROOT, "backdrops", "baked.js")] +
              glob.glob(os.path.join(ROOT, "fixtures", "*", "fixture.js"))}
    _n, bad = bake()
    if bad:
        return [], bad
    now = set(glob.glob(os.path.join(ROOT, "fixtures", "*", "fixture.js")))
    now.add(os.path.join(ROOT, "backdrops", "baked.js"))
    return [rel(p) for p in sorted(now) if sha(p) != before.get(p)], None


